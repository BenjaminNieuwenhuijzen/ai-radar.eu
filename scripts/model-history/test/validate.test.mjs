test("W10: a curator's local 'today' is never in the future, whatever the UTC time", () => {
  // 00:24 in Amsterdam (CEST) on 1 October 2026 is still 30 September in UTC; the fixture holds
  // many dates of 2026-10-01 (lastReviewedAt, lastCheckedAt), and none may warn.
  const early = { ...OPTS, now: "2026-09-30T22:24:00Z" };
  const f = validate(structuredClone(BASIC), early);
  assert.deepEqual(f.filter(x => x.code === "W10"), [], show(f));
  // A day that has not started anywhere on earth (UTC+14 is still on 1 October) does warn.
  const ds = applyPatches(structuredClone(BASIC), [{ source: "src.other-lab.site", set: [["lastCheckedAt", "2026-10-02"]] }]);
  assert.ok(validate(ds, early).some(x => x.code === "W10" && x.path.endsWith("lastCheckedAt")));
  // A timestamp is compared as an instant.
  const ts = applyPatches(structuredClone(BASIC), [{ source: "src.other-lab.site", set: [["lastCheckedAt", "2026-09-30T23:00:00Z"]] }]);
  assert.ok(validate(ts, early).some(x => x.code === "W10"));
});

