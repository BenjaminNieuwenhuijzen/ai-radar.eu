/* ---------- Patch helpers for cases.json ---------- */
const segs = p => (Array.isArray(p) ? p : String(p).split(".")).map(s => (/^\d+$/.test(s) ? +s : s));
function walk(obj, path, create) {
  const s = segs(path);
  let o = obj;
  for (const k of s.slice(0, -1)) {
    if (o[k] === undefined || o[k] === null) { if (!create) return [undefined]; o[k] = {}; }
    o = o[k];
  }
  return [o, s[s.length - 1]];
}
function applyPatches(ds, patches) {
  const lists = { model: ds.models, org: ds.organizations, family: ds.families, source: ds.sources };
  for (const p of patches) {
    if (p.add) { lists[p.add].push(structuredClone(p.value)); continue; }
    let target;
    if (p.state) target = ds.state[p.state];
    else {
      const kind = Object.keys(lists).find(k => k in p);
      target = lists[kind].find(x => x.id === p[kind]);
      if (!target) throw new Error(`fixture has no ${kind} ${p[kind]}`);
    }
    for (const [path, v] of p.set || []) { const [o, k] = walk(target, path, true); o[k] = structuredClone(v); }
    for (const path of p.unset || []) { const [o, k] = walk(target, path, false); if (o) delete o[k]; }
    for (const [path, v] of p.push || []) { const [o, k] = walk(target, path, true); (o[k] = o[k] || []).push(structuredClone(v)); }
  }
  return ds;
}

