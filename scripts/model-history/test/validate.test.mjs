/* ---------- Repository guards (temporary repository layouts) ---------- */
function tempRepo(files) {
  const root = mkdtempSync(join(tmpdir(), "mh-validate-"));
  for (const [rel, text] of Object.entries(files)) { mkdirSync(dirname(join(root, rel)), { recursive: true }); writeFileSync(join(root, rel), text); }
  return root;
}

test("E18: an id-function copy that is not byte-identical fails; a missing copy only warns", () => {
  const feed = readFileSync(join(REPO, "scripts", "build-feed.mjs"), "utf8").replace("Math.imul(h1 ^ ch, 2654435761)", "Math.imul(h1 ^ ch, 2654435762)");
  const root = tempRepo({ "scripts/build-feed.mjs": feed });
  try {
    const f = validate(structuredClone(BASIC), { ...OPTS, repoRoot: root });
    assert.ok(f.some(x => x.code === "E18" && x.level === "error" && x.file === "scripts/build-feed.mjs"), show(f));
    assert.ok(f.some(x => x.code === "E18" && x.level === "warning" && x.file === "assets/app.js"), show(f));
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test("E18: the real repository copies are byte-identical", () => {
  const root = tempRepo({});
  try {
    mkdirSync(join(root, "scripts"), { recursive: true }); mkdirSync(join(root, "assets"), { recursive: true });
    copyFileSync(join(REPO, "scripts", "build-feed.mjs"), join(root, "scripts", "build-feed.mjs"));
    // CRLF line endings (a Windows checkout) must not count as a difference.
    writeFileSync(join(root, "assets", "app.js"), readFileSync(join(REPO, "assets", "app.js"), "utf8").replace(/\r?\n/g, "\r\n"));
    const f = validate(structuredClone(BASIC), { ...OPTS, repoRoot: root });
    assert.ok(!f.some(x => x.code === "E18"), show(f));
  } finally { rmSync(root, { recursive: true, force: true }); }
});

