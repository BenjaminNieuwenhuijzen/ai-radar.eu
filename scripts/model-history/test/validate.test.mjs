/* ---------- Cases ---------- */
for (const c of CASES.cases) {
  test(`${c.code}: ${c.name}`, () => {
    const ds = applyPatches(structuredClone(BASIC), c.patch);
    const f = validate(ds, { ...OPTS, registry: c.registry ? CASES.registry : null });
    assert.deepEqual(errorCodes(f), [...c.errors].sort(), show(f));
    for (const w of c.warnings || []) assert.ok(f.some(x => x.code === w && x.level === "warning"), `expected ${w}\n${show(f)}`);
    if (c.code.startsWith("E")) assert.ok(f.some(x => x.code === c.code && x.level === "error"), `expected ${c.code}\n${show(f)}`);
  });
}

